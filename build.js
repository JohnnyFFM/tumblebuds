// Builds the installable (PWA) version of the game into ./docs for GitHub Pages.
// Usage: node build.js
// index.html is the single source (it is also what gets published as the claude.ai artifact);
// this wraps it in a full document, points it at the local three.js copy and writes the manifest + service worker.
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const out = path.join(__dirname, 'docs');
fs.mkdirSync(out, { recursive: true });

const CDN = 'https://cdnjs.cloudflare.com/ajax/libs/three.js/r128/three.min.js';
let src = fs.readFileSync(path.join(__dirname, 'index.html'), 'utf8');
// every build gets a new visible version (shown on the title screen, in Settings and in the pause menu)
{
  const m = src.match(/const VERSION='(\d+)\.(\d+)\.(\d+)',BUILT='[^']*';/);
  if (!m) throw new Error('VERSION line not found');
  const d = new Date(), p = n => String(n).padStart(2, '0');
  const ver = m[1] + '.' + m[2] + '.' + (+m[3] + 1), stamp = d.getUTCFullYear() + '-' + p(d.getUTCMonth() + 1) + '-' + p(d.getUTCDate()) + ' ' + p(d.getUTCHours()) + ':' + p(d.getUTCMinutes()) + ' UTC';
  src = src.replace(m[0], "const VERSION='" + ver + "',BUILT='" + stamp + "';");
  fs.writeFileSync(path.join(__dirname, 'index.html'), src);
  console.log('version ' + ver + ' (' + stamp + ')');
}
if (!src.includes(CDN)) throw new Error('three.js CDN tag not found');
if (!fs.existsSync(path.join(out, 'three.min.js'))) throw new Error('docs/three.min.js missing - download it from ' + CDN);
src = src.replace(CDN, 'three.min.js');

const cut = src.indexOf('</style>') + 8;
const head = src.slice(0, cut), body = src.slice(cut);
const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="description" content="Tumblebuds: The Journey Home - help the Buds get home across 20 levels.">
<meta name="theme-color" content="#1d2a33">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="apple-mobile-web-app-title" content="Tumblebuds">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="192x192" href="icon-192.png">
<link rel="apple-touch-icon" href="icon-180.png">
${head}
</head>
<body>
${body}
</body>
</html>
`;
fs.writeFileSync(path.join(out, 'index.html'), html);

fs.writeFileSync(path.join(out, 'manifest.webmanifest'), JSON.stringify({
  name: 'Tumblebuds', short_name: 'Tumblebuds',
  description: 'Help the Buds find their way home: 20 levels across beach, sea, desert, mountain and stars.',
  start_url: './', scope: './', id: './',
  display: 'fullscreen', display_override: ['fullscreen', 'standalone'],
  orientation: 'any', background_color: '#1d2a33', theme_color: '#1d2a33',
  categories: ['games'],
  icons: [
    { src: 'icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: 'icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' }
  ]
}, null, 1));

const ver = crypto.createHash('sha1').update(html).digest('hex').slice(0, 10);
fs.writeFileSync(path.join(out, 'sw.js'), `// generated by build.js - do not edit
const CACHE='tumblebuds-${ver}';
const CORE=['./','three.min.js','manifest.webmanifest','icon-192.png','icon-512.png','icon-180.png'];
self.addEventListener('install',e=>{e.waitUntil(caches.open(CACHE).then(c=>c.addAll(CORE)).then(()=>self.skipWaiting()));});
self.addEventListener('activate',e=>{e.waitUntil(caches.keys().then(ks=>Promise.all(ks.filter(k=>k!==CACHE).map(k=>caches.delete(k)))).then(()=>self.clients.claim()));});
self.addEventListener('fetch',e=>{
  const r=e.request;if(r.method!=='GET')return;
  const u=new URL(r.url),same=u.origin===location.origin,font=/fonts\\.(googleapis|gstatic)\\.com$/.test(u.hostname);
  if(!same&&!font)return;
  if(r.mode==='navigate'){ // page: fresh when online, cached when offline
    e.respondWith(fetch(r.url,{cache:'no-store'}).then(x=>{const cp=x.clone();caches.open(CACHE).then(c=>c.put('./',cp));return x;}).catch(()=>caches.match('./')));
    return;
  }
  e.respondWith(caches.match(r).then(hit=>hit||fetch(r).then(x=>{if(x.ok||x.type==='opaque'){const cp=x.clone();caches.open(CACHE).then(c=>c.put(r,cp));}return x;})));
});
`);
fs.writeFileSync(path.join(out, '.nojekyll'), '');
console.log('built docs/ (cache ' + ver + ')');
